_WEEKDAYS: tuple[str, ...] = ("월요일", "화요일", "수요일", "목요일", "금요일", "토요일", "일요일")

_WEEKDAY_TOKENS: dict[str, str] = {day: day for day in _WEEKDAYS}

_WEEKEND_ALIAS_PATTERN = re.compile("주말")
_WEEKEND_EXPANSION = "토요일 일요일"

_TOKEN_ALTERNATION = "|".join(_WEEKDAY_TOKENS)
_RANGE_PATTERN = re.compile(rf"({_TOKEN_ALTERNATION})\s*[~\-–]\s*({_TOKEN_ALTERNATION})")
_TOKEN_PATTERN = re.compile(_TOKEN_ALTERNATION)

_ALWAYS_OPEN_PATTERN = re.compile("무휴|연중개방|24시개방|24시간")

_MONTHLY_QUALIFIER_PATTERN = re.compile("매월|매달")


def _expand_range(start_day: str, end_day: str) -> list[str]:
    start_idx = _WEEKDAYS.index(start_day)
    end_idx = _WEEKDAYS.index(end_day)
    span: list[str] = []
    i = start_idx
    while True:
        span.append(_WEEKDAYS[i])
        if i == end_idx:
            break
        i = (i + 1) % len(_WEEKDAYS)
    return span


def normalize_restdate(raw: str | None) -> str:
    if raw is None:
        return NO_DATA
    text = raw.strip()
    if not text:
        return NO_DATA

    known = _KNOWN_RESTDATE_MAP.get(text)
    if known is not None:
        return known

    return _infer_from_pattern(text)


def _infer_from_pattern(text: str) -> str:
    text = _WEEKEND_ALIAS_PATTERN.sub(_WEEKEND_EXPANSION, text)

    found: set[str] = set()

    if not _MONTHLY_QUALIFIER_PATTERN.search(text):
        def _consume_range(match: re.Match[str]) -> str:
            start = _WEEKDAY_TOKENS[match.group(1)]
            end = _WEEKDAY_TOKENS[match.group(2)]
            found.update(_expand_range(start, end))
            return " "  # 범위로 이미 처리한 구간은 지워서 아래 단독 토큰 탐색에서 중복으로 안 잡히게 한다.

        remaining = _RANGE_PATTERN.sub(_consume_range, text)
        for token in _TOKEN_PATTERN.findall(remaining):
            found.add(_WEEKDAY_TOKENS[token])

    if found:
        return ",".join(day for day in _WEEKDAYS if day in found)

    if _ALWAYS_OPEN_PATTERN.search(text):
        return ALWAYS_OPEN

    return NO_DATA
