def _aliases(name: str) -> set[str]:
    aliases = {name}
    if name.endswith(("시", "군", "구")):
        aliases.add(name[:-1])
    if name.endswith("특별자치시"):
        aliases.add(name.removesuffix("특별자치시"))
    return aliases


